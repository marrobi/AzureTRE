"""Run lifecycle: configuration, submission, state reconciliation and progress."""

from __future__ import annotations

import json
import re
import uuid
from dataclasses import asdict, dataclass, field
from datetime import datetime, timedelta, timezone
from typing import Any

from .auth import User
from .batch import HeadRunner, HeadStatus
from .config import Settings
from .pipelines import Pipeline
from .store import RESULTS, RUNS, WORK, Store

TERMINAL = {"succeeded", "failed", "cancelled"}
RUN_ID_PATTERN = re.compile(r"^[a-f0-9]{12}$")
EVENTS_FILE = "events.jsonl"


def utcnow() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


@dataclass
class Run:
    id: str
    pipeline_id: str
    pipeline_name: str
    params: dict[str, Any]
    created_by: str
    created_by_name: str
    created_at: str
    status: str = "submitted"
    updated_at: str = ""
    started_at: str | None = None
    finished_at: str | None = None
    exit_code: int | None = None
    error: str | None = None
    nextflow_run_name: str | None = None
    cancel_requested_by: str | None = None
    label: str = ""
    extra: dict[str, Any] = field(default_factory=dict)

    @property
    def is_terminal(self) -> bool:
        return self.status in TERMINAL


@dataclass
class ProcessProgress:
    name: str
    submitted: int = 0
    running: int = 0
    succeeded: int = 0
    failed: int = 0
    cached: int = 0


def nextflow_config(settings: Settings, run_id: str) -> str:
    """Generate the per-run Nextflow config. Pools are pre-created; Nextflow may not create or resize them."""
    return f"""\
// Generated by the Azure TRE Nextflow portal for run {run_id}
process {{
    executor = 'azurebatch'
    queue = '{settings.worker_pool_id}'
}}

workDir = 'az://{settings.storage_container}/work/{run_id}'

// Batch runs task containers as a task user whose home directory doesn't exist in the image,
// so azcopy must keep its job plans in the task directory.
env {{
    AZCOPY_JOB_PLAN_LOCATION = '$PWD/.azcopy'
}}

azure {{
    managedIdentity {{
        clientId = '{settings.head_identity_client_id}'
    }}
    storage {{
        accountName = '{settings.storage_account}'
    }}
    batch {{
        endpoint = '{settings.batch_endpoint}'
        allowPoolCreation = false
        autoPoolMode = false
        deletePoolsOnCompletion = false
        deleteJobsOnCompletion = true
        deleteTasksOnCompletion = true
        terminateJobsOnCompletion = true
        copyToolInstallMode = 'node'
    }}
}}

weblog {{
    enabled = true
    url = 'http://127.0.0.1:8099/events'
}}
"""


class RunService:
    def __init__(self, settings: Settings, store: Store, runner: HeadRunner) -> None:
        self.settings = settings
        self.store = store
        self.runner = runner

    def create(self, user: User, pipeline: Pipeline, params: dict[str, Any], label: str = "") -> Run:
        run_id = uuid.uuid4().hex[:12]
        params = {**params, "outdir": f"az://{self.settings.storage_container}/{RESULTS}/{run_id}"}
        now = utcnow()
        run = Run(
            id=run_id,
            pipeline_id=pipeline.id,
            pipeline_name=pipeline.name,
            params=params,
            created_by=user.id,
            created_by_name=user.name,
            created_at=now,
            updated_at=now,
            label=label.strip()[:120],
        )
        self.store.write_bytes(RUNS, f"{run_id}/nextflow.config", nextflow_config(self.settings, run_id).encode())
        self.store.write_bytes(RUNS, f"{run_id}/params.json", json.dumps(params, indent=2).encode())
        self._save(run)
        env = {
            "NF_RUN_ID": run_id,
            "NF_PIPELINE": pipeline.id,
            "NF_STORAGE_ACCOUNT": self.settings.storage_account,
            "NF_STORAGE_CONTAINER": self.settings.storage_container,
            "NF_IDENTITY_CLIENT_ID": self.settings.head_identity_client_id,
            # The TRE registry, for pipelines whose tre.config uses images mirrored into it.
            "NF_CONTAINER_REGISTRY": self.settings.runtime_image.split("/", 1)[0]
            if self.settings.runtime_image
            else "",
        }
        try:
            self.runner.submit(run_id, env)
        except Exception as exc:  # surface submission failures on the run itself
            run.status, run.error, run.finished_at = "failed", f"Submission failed: {exc}", utcnow()
            self._save(run)
        return run

    def get(self, run_id: str) -> Run | None:
        if not RUN_ID_PATTERN.match(run_id):
            return None
        data = self.store.read_bytes(RUNS, f"{run_id}/run.json")
        if not data:
            return None
        raw = json.loads(data)
        known = {f for f in Run.__dataclass_fields__}
        return Run(**{k: v for k, v in raw.items() if k in known})

    def list(self) -> list[Run]:
        runs = []
        for item in self.store.list(RUNS):
            if item.name.endswith("/run.json"):
                run = self.get(item.name.split("/", 1)[0])
                if run:
                    runs.append(run)
        return sorted(runs, key=lambda r: r.created_at, reverse=True)

    def events(self, run_id: str) -> list[dict[str, Any]]:
        data = self.store.read_bytes(RUNS, f"{run_id}/{EVENTS_FILE}") or b""
        events = []
        for line in data.decode("utf-8", "replace").splitlines():
            try:
                events.append(json.loads(line))
            except ValueError:
                continue
        return events

    def progress(self, run_id: str) -> list[ProcessProgress]:
        """Latest state of each task from weblog events, aggregated by process."""
        latest: dict[str, tuple[str, str]] = {}
        for event in self.events(run_id):
            trace = event.get("trace") or {}
            task = trace.get("task_id") or trace.get("hash")
            if task is None or not trace.get("process"):
                continue
            status = str(trace.get("status") or event.get("event", "")).upper()
            latest[str(task)] = (trace["process"], status)
        processes: dict[str, ProcessProgress] = {}
        for process, status in latest.values():
            p = processes.setdefault(process, ProcessProgress(process))
            if status == "COMPLETED":
                p.succeeded += 1
            elif status == "CACHED":
                p.cached += 1
            elif status in ("FAILED", "ABORTED"):
                p.failed += 1
            elif status == "RUNNING":
                p.running += 1
            else:
                p.submitted += 1
        return list(processes.values())

    def refresh(self, run: Run) -> Run:
        if run.is_terminal:
            return run
        head = self.runner.status(run.id)
        events = self.events(run.id)
        changed = self._apply(run, head, events)
        if changed:
            run.updated_at = utcnow()
            self._save(run)
        return run

    def refresh_active(self) -> None:
        for run in self.list():
            if not run.is_terminal:
                self.refresh(run)

    def expire_work(self, now: datetime | None = None) -> int:
        """Delete intermediate files of finished runs after the retention period. Returns the number deleted."""
        cutoff = (now or datetime.now(timezone.utc)) - timedelta(days=self.settings.work_retention_days)
        finished: dict[str, bool] = {}
        deleted = 0
        for item in self.store.list(WORK):
            run_id = item.name.split("/", 1)[0]
            if run_id not in finished:
                run = self.get(run_id)
                finished[run_id] = run is None or run.is_terminal
            if finished[run_id] and item.last_modified and item.last_modified < cutoff:
                self.store.delete(WORK, item.name)
                deleted += 1
        return deleted

    def cancel(self, run: Run, user: User) -> None:
        if run.is_terminal:
            return
        if run.created_by != user.id and not user.is_owner:
            raise PermissionError("Only the person who started the run or a workspace owner can cancel it.")
        self.runner.cancel(run.id)
        run.cancel_requested_by = user.name
        run.updated_at = utcnow()
        self._save(run)

    def read_log(self, run: Run) -> str:
        log = self.store.read_bytes(RESULTS, f"{run.id}/_nextflow/nextflow.log")
        if run.is_terminal and log:
            return log.decode("utf-8", "replace")[-256 * 1024 :]
        return self.runner.read_log(run.id)

    def _apply(self, run: Run, head: HeadStatus, events: list[dict[str, Any]]) -> bool:
        before = asdict(run)
        names = [e.get("runName") for e in events if e.get("runName")]
        if names:
            run.nextflow_run_name = names[-1]
        started = any(e.get("event") == "started" for e in events)
        if head.state == "completed":
            run.exit_code = head.exit_code
            run.finished_at = head.end_time.isoformat(timespec="seconds") if head.end_time else utcnow()
            if run.cancel_requested_by:
                run.status = "cancelled"
            elif head.exit_code == 0 and not head.failure:
                run.status = "succeeded"
            else:
                run.status = "failed"
                run.error = (
                    head.failure or self._error_from_events(events) or f"Nextflow exited with code {head.exit_code}"
                )
        elif head.state == "running":
            run.status = "running" if started else "starting"
        elif head.state in ("queued", "starting"):
            run.status = "queued" if head.state == "queued" else "starting"
        if head.start_time and not run.started_at:
            run.started_at = head.start_time.isoformat(timespec="seconds")
        return asdict(run) != before

    @staticmethod
    def _error_from_events(events: list[dict[str, Any]]) -> str | None:
        for event in reversed(events):
            meta = (event.get("metadata") or {}).get("workflow") or {}
            if meta.get("errorMessage"):
                return str(meta["errorMessage"])[:2000]
        return None

    def _save(self, run: Run) -> None:
        self.store.write_bytes(RUNS, f"{run.id}/run.json", json.dumps(asdict(run), indent=2).encode())
